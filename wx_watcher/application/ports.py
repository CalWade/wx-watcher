"""Structural interfaces used at the application boundary."""

from collections.abc import Callable
from contextlib import AbstractContextManager
from pathlib import Path
from typing import Any, Protocol

from ..domain.agents import AgentJob


class SettingsRepository(Protocol):
    home: Path

    def load(self) -> dict: ...
    def update(self, **values) -> dict: ...
    def profile(self) -> dict: ...
    def add_profile(self, root, reference, label="", verification=None): ...
    def account_display(self, root, settings=None) -> dict: ...
    def save_account_names(self, root, **values) -> dict: ...
    def write_configs(self) -> tuple[Path, Path]: ...


class CredentialGateway(Protocol):
    def execute(self, request: dict) -> dict: ...


class QueryClient(Protocol):
    def request(self, route: str, data=None) -> dict: ...


class AgentGateway(Protocol):
    """A client may be local, embedded or remote; job identity must stay stable."""

    provider_id: str

    def prepare(self) -> dict: ...
    def status(self) -> dict: ...
    def submit(self, id: str, prompt: str) -> AgentJob: ...
    def poll(self, id: str) -> AgentJob: ...


class DeliveryGateway(Protocol):
    def chats(self) -> dict: ...
    def send(
        self, chat: str, text: str, idempotency_key: str, dry_run=False
    ) -> dict: ...
    def confirm_readback(self, message_id: str, text: str) -> bool: ...


class Supervisor(Protocol):
    def running(self) -> bool: ...
    def start(self) -> dict: ...
    def stop(self) -> dict: ...
    def status(self) -> dict: ...


class MessageReader(Protocol):
    config: Any

    def rows(self, source: Path, sql: str) -> list[dict]: ...
    def close(self): ...


class MessageSource(Protocol):
    root: Path | None
    display_name: str

    def resolve(self) -> str: ...
    def shards(self) -> list[Path]: ...
    def read_shard(self, path, after, limit=1000) -> tuple[str, list[dict]]: ...


class TaskRepository(Protocol):
    def get_meta(self, key, default=None): ...
    def set_meta(self, key, value): ...
    def bind_scope(self, scope): ...
    def save(self, task: dict): ...
    def save_many(self, tasks: list[dict]): ...
    def task(self, id: str) -> dict | None: ...
    def tasks(self, statuses=None, limit=100) -> list[dict]: ...
    def accept(self, task: dict, cursor: int): ...
    def enqueue_pending(self, task: dict, received: float): ...
    def pending(self, limit=10) -> list[dict]: ...
    def commit_batch(self, task: dict, ids: list[str]): ...
    def record_inference(self, task: dict, day: str, count_call: bool): ...
    def complete_tick(self, timestamp: str, wall_time: float, retention_days: int): ...
    def counts(self) -> dict: ...
    def close(self): ...
    def update_metadata(self, values: dict): ...


class TaskAccess(Protocol):
    def open(self) -> AbstractContextManager[TaskRepository]: ...
    def recent(self) -> list[dict]: ...
    def reset_cursor(self) -> dict: ...
    def has_inflight(self) -> bool: ...


class CaptureGateway(Protocol):
    def preflight(self, root="", discover_account=False) -> dict: ...
    def start(self, root="", discover_account=False) -> dict: ...
    def status(self, id: str) -> dict: ...
    def cancel(self, id: str) -> dict: ...
    def login_page_ready(self, id: str) -> dict: ...
    def recover(self, id: str) -> dict: ...
    def sessions(self) -> list[dict]: ...


class Clock(Protocol):
    def timestamp(self) -> str: ...
    def time(self) -> float: ...
    def monotonic(self) -> float: ...
    def sleep(self, seconds: float): ...


Action = Callable[[str, dict], dict]


class AccountsContext(Protocol):
    state: SettingsRepository

    def accounts(self) -> list[dict]: ...
    def account_status(self) -> dict: ...
    def active_roots(self) -> list[Path]: ...
    def canonical_root(self, value: str) -> Path: ...
    def refresh_account_names(self, root, quiet=False) -> dict: ...
    def require_current_account(self, profile=None): ...
    def require_local_account(self): ...
    def reader(self) -> MessageReader: ...
    def conversations(self, query="") -> list[dict]: ...
    def read_conversations(self, query="") -> list[dict]: ...


class CredentialsContext(Protocol):
    state: SettingsRepository
    services: Supervisor
    capture: CaptureGateway

    def credential_request(self, data: dict) -> dict: ...
    def load_key_file(self, value: str) -> bytes: ...
    def canonical_root(self, value: str) -> Path: ...
    def refresh_account_names(self, root, quiet=False) -> dict: ...
    def close_preview(self): ...


class SettingsContext(Protocol):
    tasks: TaskAccess

    def validate_agent(self, provider_id: str, options: dict): ...

    state: SettingsRepository
    services: Supervisor
    preview_reader: MessageReader | None

    def require_current_account(self, profile=None): ...
    def require_local_account(self): ...
    def credential_request(self, data: dict) -> dict: ...
    def refresh_account_names(self, root, quiet=False) -> dict: ...
    def close_preview(self): ...
    def select_passages(self, files, query): ...
    def perform(self, operation: str, data: dict) -> dict: ...
    def login_installed(self) -> bool: ...
    def manage_login(self, action: str) -> dict: ...


class ConnectionsContext(Protocol):
    state: SettingsRepository
    services: Supervisor
    clock: Clock

    def agent(self) -> AgentGateway: ...
    def connect_existing(self) -> dict: ...
    def check_first_connection(self, root: str, discover: bool) -> dict: ...
    def feishu(self) -> DeliveryGateway: ...


class RuntimeContext(Protocol):
    state: SettingsRepository
    services: Supervisor

    def require_current_account(self, profile=None): ...
    def perform(self, operation: str, data: dict) -> dict: ...
    def assert_data_access(self): ...
    def agent(self) -> AgentGateway: ...
    def doctor(self) -> dict: ...
    def records(self) -> list[dict]: ...


class TasksContext(Protocol):
    services: Supervisor
    tasks: TaskAccess
    clock: Clock

    def review_task(self, data: dict) -> dict: ...


class EventRepository(Protocol):
    def had_live_events(self) -> bool: ...
    def bind_scope(self, scope: str): ...
    def initialized(self) -> bool: ...
    def watermarks(self) -> dict: ...
    def apply(self, batches, baseline: bool) -> int: ...
    def prune(self, cutoff: int): ...
    def event_cursor(self) -> int: ...
